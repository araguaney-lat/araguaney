type Ficha = BoxFicha | PalletFicha

async function fetchFicha(code: string): Promise<Ficha | null> {
  try {
    const res = await fetch(`${API_URL}/v1/public/qr/${encodeURIComponent(code)}`, {
      next: { revalidate: 60, tags: [`qr-${code}`] },
    })
    if (!res.ok) return null
    return res.json()
  } catch {
    return null
  }
}

export async function generateMetadata({
  params,
}: {
  params: Promise<{ code: string }>
}): Promise<Metadata> {
  const { code } = await params
  const [ficha, locale] = await Promise.all([fetchFicha(code), detectLocale()])
  const L = LABELS[locale]

  if (!ficha) {
    return { title: L.notFound, robots: { index: false, follow: false } }
  }

  const title =
    ficha.kind === "box" ? `${ficha.display_name} — QR` : `${L.pallet} ${ficha.code} — QR`
  const description =
    ficha.kind === "box"
      ? `${ficha.code} · ${ficha.center_name} · ${ficha.quantity} ${ficha.unit}`
      : `${ficha.code} · ${ficha.center_name} · ${ficha.box_count} ${L.boxesWord}`

  return {
    title,
    description,
    alternates: { canonical: `/qr/${ficha.code}` },
    openGraph: { title, description, images: [DEFAULT_OG_IMAGE] },
    twitter: { card: "summary_large_image", title, description, images: [DEFAULT_OG_IMAGE] },
  }
}

export default async function QrFichaPage({
  params,
}: {
  params: Promise<{ code: string }>
}) {
  const { code } = await params
  const [ficha, locale] = await Promise.all([fetchFicha(code), detectLocale()])

  if (!ficha) notFound()
  const L = LABELS[locale]

  const statusColor = STATUS_COLORS[ficha.status] ?? "bg-zinc-100 text-zinc-700"
  const statusLabel = L.statuses[ficha.status] ?? ficha.status

  return (
    <div className="min-h-screen bg-zinc-50">
      <div className="mx-auto max-w-lg px-4 py-8">
        {/* Header */}
        <div className="mb-6">
          <p className="text-xs text-zinc-500 font-mono mb-1">{ficha.code}</p>
          <div className="flex items-center gap-3">
            <h1 className="text-2xl font-bold text-zinc-900 leading-tight">
              {ficha.kind === "box" ? ficha.display_name : `${L.pallet} ${ficha.code}`}
            </h1>
            <span className={`shrink-0 rounded-full px-3 py-1 text-sm font-medium ${statusColor}`}>
              {statusLabel}
            </span>
          </div>
        </div>

        {ficha.kind === "box" && <BoxSection ficha={ficha} L={L} />}
        {ficha.kind === "pallet" && <PalletSection ficha={ficha} L={L} />}

        {/* Timeline */}
        {ficha.events.length > 0 && (
          <section className="mt-8">
            <h2 className="text-sm font-semibold text-zinc-500 uppercase tracking-wide mb-4">
              {L.history}
            </h2>
            <StatusTimeline events={ficha.events} />
          </section>
        )}

        <p className="mt-10 text-center text-xs text-zinc-300">{L.footer}</p>
      </div>
    </div>
  )
}

function Row({ label, value }: { label: string; value: React.ReactNode }) {
  return (
    <div className="flex justify-between py-2.5 border-b border-zinc-100 last:border-0">
      <span className="text-sm text-zinc-500">{label}</span>
      <span className="text-sm font-medium text-zinc-900 text-right max-w-[60%]">{value ?? "—"}</span>
    </div>
  )
}

function BoxSection({ ficha, L }: { ficha: BoxFicha; L: QrLabels }) {
  return (
    <>
      {/* Product details */}
      <section className="rounded-xl border border-zinc-200 bg-white divide-y divide-zinc-100 mb-4">
        <div className="px-4 py-3">
          <p className="text-xs font-semibold text-zinc-500 uppercase tracking-wide">{L.product}</p>
        </div>
        <div className="px-4">
          <Row label={L.category} value={L.categories[ficha.category] ?? ficha.category} />
          {ficha.inn_name && <Row label={L.inn} value={ficha.inn_name} />}
          {ficha.strength && <Row label={L.strength} value={ficha.strength} />}
          {ficha.form && <Row label={L.form} value={ficha.form} />}
        </div>
      </section>

      {/* Lot / expiry */}
      <section className="rounded-xl border border-zinc-200 bg-white divide-y divide-zinc-100 mb-4">
        <div className="px-4 py-3">
          <p className="text-xs font-semibold text-zinc-500 uppercase tracking-wide">{L.batchExpiry}</p>
        </div>
        <div className="px-4">
          <Row label={L.batch} value={ficha.batch} />
          <Row
            label={L.expiry}
            value={
              ficha.expiry_date
                ? new Date(ficha.expiry_date).toLocaleDateString(L.dateLocale, { year: "numeric", month: "long", day: "numeric" })
                : null
            }
          />
        </div>
      </section>

      {/* Quantity & weight */}
      <section className="rounded-xl border border-zinc-200 bg-white divide-y divide-zinc-100 mb-4">
        <div className="px-4 py-3">
          <p className="text-xs font-semibold text-zinc-500 uppercase tracking-wide">{L.quantityWeight}</p>
        </div>
        <div className="px-4">
          <Row label={L.quantity} value={`${ficha.quantity} ${ficha.unit}`} />
          <Row label={L.weight} value={fmt(ficha.weight_kg)} />
        </div>
      </section>

      {/* Context */}
      <section className="rounded-xl border border-zinc-200 bg-white divide-y divide-zinc-100">
        <div className="px-4 py-3">
          <p className="text-xs font-semibold text-zinc-500 uppercase tracking-wide">{L.origin}</p>
        </div>
        <div className="px-4">
          <Row label={L.center} value={ficha.center_name} />
          {ficha.campaign_name && <Row label={L.campaign} value={ficha.campaign_name} />}
          <Row
            label={L.sealed}
            value={
              ficha.sealed_at
                ? new Date(ficha.sealed_at).toLocaleString(L.dateLocale, { day: "numeric", month: "short", year: "numeric" })
                : null
            }
          />
        </div>
      </section>
    </>
  )
}

function PalletSection({ ficha, L }: { ficha: PalletFicha; L: QrLabels }) {
  return (
    <>
      {/* Summary */}
      <section className="rounded-xl border border-zinc-200 bg-white divide-y divide-zinc-100 mb-4">
        <div className="px-4 py-3">
          <p className="text-xs font-semibold text-zinc-500 uppercase tracking-wide">{L.summary}</p>
        </div>
        <div className="px-4">
          <Row label={L.center} value={ficha.center_name} />
          <Row label={L.boxesRow} value={String(ficha.box_count)} />
          <Row label={L.totalWeight} value={fmt(ficha.total_weight_kg)} />
          <Row
            label={L.closed}
            value={
              ficha.closed_at
                ? new Date(ficha.closed_at).toLocaleString(L.dateLocale, { day: "numeric", month: "short", year: "numeric" })
                : null
            }
          />
        </div>
      </section>

      {/* Box list */}
      {ficha.boxes.length > 0 && (
        <section className="rounded-xl border border-zinc-200 bg-white overflow-hidden">
          <div className="px-4 py-3 border-b border-zinc-100">
            <p className="text-xs font-semibold text-zinc-500 uppercase tracking-wide">
              {L.contents(ficha.boxes.length)}
            </p>
          </div>
          <ul className="divide-y divide-zinc-100">
            {ficha.boxes.map((b, i) => (
              <li key={i} className="flex items-center justify-between px-4 py-3 gap-2">
                <div className="min-w-0">
                  <p className="text-sm font-medium text-zinc-900 truncate">{b.display_name}</p>
                  <p className="text-xs text-zinc-500">{L.categories[b.category] ?? b.category}</p>
                </div>
                <div className="text-right shrink-0">
                  <p className="text-sm font-medium text-zinc-900">{b.quantity} {b.unit}</p>
                  <p className="text-xs text-zinc-500">{fmt(b.weight_kg)}</p>
                </div>
              </li>
            ))}
          </ul>
        </section>
      )}
    </>
  )
}
