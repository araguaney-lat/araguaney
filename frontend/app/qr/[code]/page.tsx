type Loc = "es" | "en"

// This page is scanned from a physical QR (not URL-locale, not SEO-enumerable).
// The inventory DATA is Spanish (admin/catalog); only the UI LABELS are localized
// via the scanner's browser language, so an international volunteer in the field
// reads "Product / Batch / Expiry" instead of "Producto / Lote / Caducidad".
async function detectLocale(): Promise<Loc> {
  const h = await headers()
  const al = (h.get("accept-language") ?? "").toLowerCase()
  return al.startsWith("en") ? "en" : "es"
}

